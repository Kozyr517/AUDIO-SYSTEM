void anim_cat3_draw(uint16_t x, uint16_t y) {
    static uint8_t current_frame = 0;
    static uint8_t delay_counter = 0;
    
    // Кількість викликів anim_cat3_draw(), протягом яких утримується один кадр.
    // Збільшуйте це значення для сповільнення (наприклад, 5, 8 або 10).
    const uint8_t FRAME_HOLD_COUNT = 6; 
    
    const uint8_t *frame_bitmap = cat3_frames[current_frame];
    
    // Передаємо uint16_t напряму без кастування до uint8_t
    LCD_DrawBitmap(&lcd, x, y, frame_bitmap, CAT3_FRAME_WIDTH, CAT3_FRAME_HEIGHT, 1);
    
    delay_counter++;
    if (delay_counter >= FRAME_HOLD_COUNT) {
        delay_counter = 0;
        current_frame = (current_frame + 1) % CAT3_ANIMATION_FRAMES;
    }
}